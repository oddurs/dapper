// Emits ground truth from d3 for dapper's ticks and scale ports.
//
// Output is generated *Gleam source*, not JSON. The plan said JSON, but source
// is strictly better here: it needs no JSON parser and no file IO at test time,
// which keeps dapper's dev dependencies from growing for the sake of a fixture
// file. It also matches how the font advance table will be shipped (L5), so the
// repo has one convention for generated data rather than two.
//
//   cd scripts && npm install && npm run gen
//
// Regenerate only when the covered cases change. The output is committed, so a
// contributor never needs Node to run the suite.

import { writeFileSync } from "node:fs";
import { ticks, tickIncrement, nice } from "d3-array";
import { scaleBand, scalePoint } from "d3-scale";

/** A Gleam float literal that round-trips exactly. */
function f(x) {
  if (Object.is(x, -0)) return "0.0";
  const s = String(x);
  if (s.includes("e")) {
    const [m, e] = s.split("e");
    return `${m.includes(".") ? m : m + ".0"}e${e}`;
  }
  return s.includes(".") ? s : s + ".0";
}

const list = (xs, fmt) => `[${xs.map(fmt).join(", ")}]`;

/**
 * Gleam has no NaN or Infinity — out-of-range literals are a compile error and
 * there is no way to construct one. d3 does produce them: `tickIncrement` on a
 * reversed range takes log10 of a negative step and returns NaN.
 *
 * Such cases are dropped from the fixtures and reported, never dropped
 * silently. What dapper should do with a reversed range is a design question
 * these fixtures cannot answer, so they must not appear to have answered it.
 */
const finite = (x) => Number.isFinite(x);
const allFinite = (xs) => xs.every(finite);
const dropped = [];

// Ranges chosen to hit the places a 1-2-5 implementation goes wrong: exact
// powers of ten, ranges that force a fractional step, negative and
// zero-crossing domains, reversed bounds, and magnitudes far from 1.
const RANGES = [
  [0, 1, 10], [0, 1, 5], [0, 1, 3], [0, 1, 2], [0, 1, 1],
  [0, 10, 10], [0, 100, 10], [0, 1000, 5],
  [1, 9, 5], [0, 0.5, 5], [0, 0.1, 5], [0, 0.05, 5],
  [-1, 1, 10], [-5, 5, 5], [-100, -10, 5],
  [1, 1, 5], [0, 0, 5],
  [10, 0, 5], [1, -1, 5],
  [0.001, 0.002, 5], [1e6, 2e6, 5], [1e-7, 2e-7, 5],
  [123, 456, 7], [2.5, 7.5, 4], [-0.3, 0.7, 5],
];

const BANDS = [
  { n: 3, lo: 0, hi: 300, pi: 0, po: 0, align: 0.5 },
  { n: 3, lo: 0, hi: 300, pi: 0.1, po: 0.1, align: 0.5 },
  { n: 4, lo: 0, hi: 100, pi: 0.2, po: 0, align: 0.5 },
  { n: 4, lo: 0, hi: 100, pi: 0.2, po: 0.2, align: 0 },
  { n: 4, lo: 0, hi: 100, pi: 0.2, po: 0.2, align: 1 },
  { n: 1, lo: 0, hi: 50, pi: 0.5, po: 0.25, align: 0.5 },
  { n: 5, lo: 20, hi: 220, pi: 0.05, po: 0.5, align: 0.5 },
  // Padding that consumes the whole range: bandwidth collapses to zero.
  { n: 2, lo: 0, hi: 100, pi: 1, po: 0, align: 0.5 },
];

const POINTS = [
  { n: 3, lo: 0, hi: 300, po: 0, align: 0.5 },
  { n: 4, lo: 0, hi: 90, po: 0.5, align: 0.5 },
  { n: 1, lo: 0, hi: 100, po: 0, align: 0.5 },
];

const domainOf = (n) => Array.from({ length: n }, (_, i) => `c${i}`);

const header = `//// GENERATED by scripts/gen-d3-fixtures.mjs — do not edit by hand.
////
//// Ground truth from d3-array 3.2.4 and d3-scale 4.0.2. dapper's tick and
//// scale implementations are ports, and a port is only a port if it is checked
//// against the original. These fixtures are what make that check possible
//// without requiring Node to run the suite.
////
//// Regenerate with: cd scripts && npm install && npm run gen

pub type TicksCase {
  TicksCase(start: Float, stop: Float, count: Int, ticks: List(Float))
}

pub type IncrementCase {
  IncrementCase(start: Float, stop: Float, count: Int, increment: Float)
}

pub type NiceCase {
  NiceCase(start: Float, stop: Float, count: Int, lo: Float, hi: Float)
}

pub type BandCase {
  BandCase(
    n: Int,
    lo: Float,
    hi: Float,
    padding_inner: Float,
    padding_outer: Float,
    align: Float,
    bandwidth: Float,
    step: Float,
    positions: List(Float),
  )
}

pub type PointCase {
  PointCase(
    n: Int,
    lo: Float,
    hi: Float,
    padding: Float,
    align: Float,
    step: Float,
    positions: List(Float),
  )
}
`;

const ticksCases = RANGES.flatMap(([a, b, c]) => {
  const t = ticks(a, b, c);
  if (!allFinite(t)) {
    dropped.push(`ticks(${a}, ${b}, ${c})`);
    return [];
  }
  return [`  TicksCase(${f(a)}, ${f(b)}, ${c}, ${list(t, f)})`];
}).join(",\n");

const incrementCases = RANGES.flatMap(([a, b, c]) => {
  const i = tickIncrement(a, b, c);
  if (!finite(i)) {
    dropped.push(`tickIncrement(${a}, ${b}, ${c})`);
    return [];
  }
  return [`  IncrementCase(${f(a)}, ${f(b)}, ${c}, ${f(i)})`];
}).join(",\n");

const niceCases = RANGES.flatMap(([a, b, c]) => {
  const [lo, hi] = nice(a, b, c);
  if (!finite(lo) || !finite(hi)) {
    dropped.push(`nice(${a}, ${b}, ${c})`);
    return [];
  }
  return [`  NiceCase(${f(a)}, ${f(b)}, ${c}, ${f(lo)}, ${f(hi)})`];
}).join(",\n");

const bandCases = BANDS.map((t) => {
  const s = scaleBand()
    .domain(domainOf(t.n))
    .range([t.lo, t.hi])
    .paddingInner(t.pi)
    .paddingOuter(t.po)
    .align(t.align);
  const pos = domainOf(t.n).map((d) => s(d));
  return `  BandCase(${t.n}, ${f(t.lo)}, ${f(t.hi)}, ${f(t.pi)}, ${f(t.po)}, ${f(t.align)}, ${f(s.bandwidth())}, ${f(s.step())}, ${list(pos, f)})`;
}).join(",\n");

const pointCases = POINTS.map((t) => {
  const s = scalePoint()
    .domain(domainOf(t.n))
    .range([t.lo, t.hi])
    .padding(t.po)
    .align(t.align);
  const pos = domainOf(t.n).map((d) => s(d));
  return `  PointCase(${t.n}, ${f(t.lo)}, ${f(t.hi)}, ${f(t.po)}, ${f(t.align)}, ${f(s.step())}, ${list(pos, f)})`;
}).join(",\n");

const body = `
pub fn ticks_cases() -> List(TicksCase) {
  [
${ticksCases},
  ]
}

pub fn increment_cases() -> List(IncrementCase) {
  [
${incrementCases},
  ]
}

pub fn nice_cases() -> List(NiceCase) {
  [
${niceCases},
  ]
}

pub fn band_cases() -> List(BandCase) {
  [
${bandCases},
  ]
}

pub fn point_cases() -> List(PointCase) {
  [
${pointCases},
  ]
}
`;

writeFileSync(new URL("../test/d3_fixtures.gleam", import.meta.url), header + body);
console.log(
  `wrote test/d3_fixtures.gleam — ${RANGES.length} ranges, ${BANDS.length} band, ${POINTS.length} point`
);
if (dropped.length) {
  console.log(`dropped ${dropped.length} non-finite case(s):`);
  for (const d of dropped) console.log(`  ${d}`);
}
